/** Blocked ranges are generated relative to today so the demo availability
 *  filter always has something to show. Offsets are in days. */
function daysFromNow(offset) {
  const d = new Date()
  d.setHours(12, 0, 0, 0)
  d.setDate(d.getDate() + offset)
  return d.toISOString().slice(0, 10)
}

function blocked(...pairs) {
  return pairs.map(([from, to]) => ({ from: daysFromNow(from), to: daysFromNow(to) }))
}

